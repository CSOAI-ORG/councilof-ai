"""Render an evidence report from ONLY the sealed .eval logs + evidence_manifest.json.

No GSPC service, no network: stdlib + inspect_ai.log (local file reader) only.
Fails closed: any hash or Merkle mismatch is printed as INVALID in the report.
Usage: python report_from_logs.py evidence/  -> evidence/report.md, evidence/report.html
"""
import hashlib, html, json, sys
from pathlib import Path
from inspect_ai.log import read_eval_log

sys.path.insert(0, str(Path(__file__).parent))
from seal_evidence import merkle_root, sha256_file  # same rule as the sealer


def short(x, n=140):
    s = "" if x is None else str(x).replace("\n", " ")
    return s if len(s) <= n else s[: n - 1] + "…"


def main(ev_dir: str = "evidence") -> None:
    ev = Path(ev_dir)
    man = json.loads((ev / "evidence_manifest.json").read_text())
    checks, leaves = [], []
    for r in man["logs"]:
        p = ev / "logs" / r["file"]
        got = sha256_file(p) if p.exists() else "MISSING"
        checks.append((r["file"], r["sha256"], got, "VALID" if got == r["sha256"] else "INVALID"))
        leaves.append(got if got != "MISSING" else "00" * 32)
    root = merkle_root(leaves)
    root_state = "VALID" if root == man["merkle_root"] else "INVALID"

    md = ["# Inspect evidence report (generated from sealed logs only)", "",
          "Generated by `report_from_logs.py` from the `.eval` files and `evidence_manifest.json` alone, "
          "with no GSPC service and no network calls.", "",
          f"- Manifest schema: `{man['schema']}`; sealed at `{man['sealed_at']}`",
          f"- Attestation: **{man['attestation']}**. {man['attestation_note']}",
          f"- Merkle root (manifest): `{man['merkle_root']}`",
          f"- Merkle root (recomputed): `{root}`: **{root_state}**", "",
          f"> **Caveat.** {man['caveat']}", "",
          "## File integrity", "", "| file | sha256 (manifest) | recomputed | state |", "|---|---|---|---|"]
    md += [f"| {f} | `{a[:16]}…` | `{b[:16]}…` | **{s}** |" for f, a, b, s in checks]

    for r in man["logs"]:
        log = read_eval_log(str(ev / "logs" / r["file"]))
        e = log.eval
        md += ["", f"## {e.task}: {e.model}", "",
               f"- Run kind: **{r['run_kind']}**",
               f"- Task version `{e.task_version}`; task args `{r['task_args']}`; status `{log.status}`",
               f"- Dataset `{r['dataset']}` @ `{r['dataset_revision']}` (pin read from {r['revision_pin_source']})",
               f"- Samples run {r['samples_run']} of {r['dataset_size']}; inspect_ai {r['inspect_ai']}"
               + (f", inspect_evals {r['inspect_evals']}" if r['inspect_evals'] else ""),
               f"- GSPC axes this task maps to: {r['gspc_axes'] or 'n/a'}",
               f"- Created {e.created}; eval_id `{e.eval_id}`", ""]
        if log.results:
            md += ["| scorer | metric | value |", "|---|---|---|"]
            for s in log.results.scores:
                md += [f"| {s.name} | {k} | {v.value:.4g} |" for k, v in s.metrics.items()]
        md += ["", "| sample id | target | model output (truncated) | score |", "|---|---|---|---|"]
        for s in (log.samples or [])[:10]:
            sc = "; ".join(f"{k}={v.value}" for k, v in (s.scores or {}).items())
            out = s.output.completion if s.output else ""
            md.append(f"| {s.id} | {short(s.target, 40)} | {short(out, 80)} | {short(sc, 60)} |")
    md += ["", "## What this report does and does not show", "",
           "- It shows that established Inspect tasks can be executed, logged, content-addressed and re-reported "
           "without any GSPC service in the loop.",
           "- mockllm rows measure nothing about any model. The single real-model row (Qwen2.5-0.5B-Instruct, n=10) is a "
           "smoke run; its interval is too wide for any comparative claim.",
           "- The `.eval` header does not carry the HF dataset revision; the pin in this report comes from the manifest, "
           "which read it from each task's source constant at seal time."]
    text = "\n".join(md) + "\n"
    (ev / "report.md").write_text(text)

    # minimal self-contained HTML: markdown tables rendered as <pre> blocks per section, escaped
    body = []
    for block in text.split("\n## "):
        body.append(f"<section><pre>{html.escape(('## ' if body else '') + block)}</pre></section>")
    (ev / "report.html").write_text(
        "<!doctype html><meta charset='utf-8'><title>Inspect evidence report</title>"
        "<style>body{font:14px/1.4 system-ui;margin:2em;max-width:1200px}pre{white-space:pre-wrap}</style>"
        + "".join(body))
    print(root_state, sum(c[3] == "VALID" for c in checks), "of", len(checks), "files VALID")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "evidence")
