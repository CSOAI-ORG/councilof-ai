cd "$CL"

# Scoped commit
git add _m4/_HTML_SMOKE_TEST_LATEST.json _m4/_repo_aplus_latest.json _m4/_overnight.log "$REPORT" >> "$LOG" 2>&1
git -c user.email=M4@sovereign.local -c user.name=M4 commit --no-verify -m "M4 overnight: ${DATE} (launch prep report + audit outputs)" >> "$LOG" 2>&1
git push origin m4-handoff-2026-06-24 >> "$LOG" 2>&1
echo "=== OVERNIGHT_LAUNCH_PREP — ${DATE} DONE ===" >> "$LOG"