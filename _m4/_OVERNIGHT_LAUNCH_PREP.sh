# Bundle refresh
BUNDLE=/Users/nicholas/Desktop/CSOAI_MEOK_HANDOFF_2026-06-26
mkdir -p "$BUNDLE/strategy"
cp _m4/_HTML_SMOKE_TEST_LATEST.json _m4/_repo_aplus_latest.json UPSTREAM_PR_STATUS.json HEADLINE_2026-06-29.md LAUNCH_STATE_2026-06-29.md "$REPORT" "$BUNDLE/strategy/" 2>/dev/null || true
cd /Users/nicholas/Desktop && rm -f CSOAI_MEOK_HANDOFF_2026-06-26.zip && zip -r CSOAI_MEOK_HANDOFF_2026-06-26.zip CSOAI_MEOK_HANDOFF_2026-06-26 -x "*.DS_Store" >/dev/null 2>&1
