#!/usr/bin/env node
/**
 * generate-blog-index.mjs — a light, derived index of client/src/data/blog-content.ts.
 *
 *   node scripts/generate-blog-index.mjs          # (re)write client/src/data/blog-index.json
 *   node scripts/generate-blog-index.mjs --check  # exit 1 if the committed index is stale
 *
 * WHY. blog-content.ts is ~500 KB of article HTML. The head producer (client/src/lib/seoHead.ts),
 * the withdrawal notice and the blog JSON-LD need only each post's slug, headline, description,
 * dates, author and cited sources — a few KB. Importing the full dataset into the app shell to
 * get those would put half a megabyte in the main chunk. So the index is derived at build time
 * from the dataset's OWN fields and JSON-LD, never typed: a post with no datePublished in its
 * JSON-LD gets no date here either (UNMEASURED is first-class for dates too).
 *
 * Wired into `build:client` before generate-route-manifest. Fail-SOFT like its sibling: on any
 * parse problem the existing index is left untouched rather than replaced with an empty one.
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = join(ROOT, "client/src/data/blog-content.ts");
const OUT = join(ROOT, "client/src/data/blog-index.json");
const CHECK = process.argv.includes("--check");

const NAMED = { amp: "&", lt: "<", gt: ">", quot: '"', apos: "'", nbsp: " ", mdash: "—", ndash: "–", hellip: "…", rsquo: "’", lsquo: "‘" };
export function decodeEntities(s) {
  return String(s).replace(/&(#x[0-9a-f]+|#\d+|[a-z]+);/gi, (whole, body) => {
    if (body[0] === "#") {
      const code = body[1] === "x" || body[1] === "X" ? parseInt(body.slice(2), 16) : parseInt(body.slice(1), 10);
      return Number.isFinite(code) ? String.fromCodePoint(code) : whole;
    }
    return NAMED[body.toLowerCase()] ?? whole;
  });
}

const OWN_HOSTS = /(^|\.)(csoai\.org|councilof\.ai)$/i;

/** External http(s) links the article body cites, in order, deduplicated. Own-site links are not sources. */
export function sourcesOf(html) {
  const out = [];
  for (const m of String(html).matchAll(/<a\b[^>]*href=["'](https?:\/\/[^"'#\s]+)["']/gi)) {
    const url = m[1];
    let host = "";
    try { host = new URL(url).hostname; } catch { continue; }
    if (OWN_HOSTS.test(host) || out.includes(url)) continue;
    out.push(url);
  }
  return out;
}

/** Parse the exported array literal without executing the module. */
export function parseBlogData(src) {
  const m = String(src).match(/export const blogdata[^=]*=\s*(\[[\s\S]*?\n\]);\n/);
  if (!m) throw new Error("blogdata array literal not found");
  try { return JSON.parse(m[1]); } catch { /* not strict JSON (comments, trailing commas) */ }
  return new Function(`return (${m[1]});`)();
}

export function buildIndex(data) {
  const posts = [];
  for (const p of data) {
    let ld = null;
    for (const raw of p.ldJson ?? []) {
      try { const j = JSON.parse(raw); if (j && j["@type"] === "BlogPosting") { ld = j; break; } } catch { /* skip */ }
    }
    const headline = decodeEntities(p.ogTitle || ld?.headline || p.title.replace(/\s*\|\s*CSOAI Blog\s*$/i, ""));
    const row = {
      slug: p.slug,
      headline,
      description: decodeEntities(p.ogDescription || p.description || ld?.description || ""),
      sources: sourcesOf(p.content),
    };
    if (typeof ld?.datePublished === "string" && ld.datePublished) row.datePublished = ld.datePublished;
    if (typeof ld?.dateModified === "string" && ld.dateModified) row.dateModified = ld.dateModified;
    if (ld?.author && typeof ld.author === "object" && typeof ld.author.name === "string") {
      row.author = { type: ld.author["@type"] || "Organization", name: ld.author.name };
    }
    posts.push(row);
  }
  posts.sort((a, b) => a.slug.localeCompare(b.slug));
  return {
    $comment: "GENERATED by scripts/generate-blog-index.mjs from client/src/data/blog-content.ts — do not hand-edit. Every field is read from the post's own data or JSON-LD; absent fields are absent, never invented.",
    source: "client/src/data/blog-content.ts",
    posts,
  };
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  try {
    const body = JSON.stringify(buildIndex(parseBlogData(readFileSync(SRC, "utf8"))), null, 2) + "\n";
    const prev = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
    if (CHECK) {
      if (prev !== body) { console.error("[blog-index] client/src/data/blog-index.json is stale — run node scripts/generate-blog-index.mjs"); process.exit(1); }
      console.log("[blog-index] up to date");
    } else {
      if (prev !== body) writeFileSync(OUT, body);
      console.log(`[blog-index] ${JSON.parse(body).posts.length} posts -> client/src/data/blog-index.json`);
    }
  } catch (e) {
    console.warn(`[blog-index] skipped (${e.message}) — existing index kept.`);
    process.exit(CHECK ? 1 : 0);
  }
}
