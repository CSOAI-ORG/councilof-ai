#!/usr/bin/env node
/**
 * scripts/a2a-tool-cards.mjs — the ONE producer of public/.well-known/agents/*.json.
 *
 * WHY THIS EXISTS (2026-09-22, found during the fleet-lock reconciliation)
 * The per-tool cards were hand-written in #1883 and each declared
 *   supportedInterfaces[0].url = https://councilof.ai/api/a2a   (binding JSONRPC, A2A 1.0)
 *   skills[0].examples[0]     = SendMessage with Part.data {"skill":"<tool>","input":{}}
 * but functions/api/a2a.ts SKILL_IDS never contained a tool name. A stranger who followed a card
 * got `unknown skill; choose one of: …` from the door it named — live, verified 2026-09-22.
 * Seven of the thirteen examples also showed `"input":{}` for tools whose MCP inputSchema has
 * REQUIRED arguments. A2A v1.0 §8.3.1: each interface MUST accurately declare its transport and
 * URL. These tools are served by MCP tools/call at POST /mcp and nowhere else, so that is what
 * the card now says: binding MCP, the door the fleet lock names, and a tools/call example built
 * from the tool's own inputSchema. The card is generated from the same manifests the door serves
 * (gspc-tools.json + paid-tools.json) and the fleet lock, so the three cannot drift apart:
 * functions/api/a2a-tool-cards.test.ts fails when the committed bytes differ from this output.
 *
 *   node scripts/a2a-tool-cards.mjs --check   # exit 1 and list every drifted file
 *   node scripts/a2a-tool-cards.mjs --write   # regenerate in place
 *
 * Measurement, not certification. No count in the output is typed: every number is derived
 * from the lock's names.
 */
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const AGENTS_DIR = resolve(ROOT, "public/.well-known/agents");

const readJson = (p) => JSON.parse(readFileSync(resolve(ROOT, p), "utf8"));

/**
 * The MCP protocol version the live door negotiated on `initialize`
 * (POST https://councilof.ai/mcp, 2026-09-22: result.protocolVersion = "2025-06-18",
 * serverInfo csoai-gspc-mcp 1.4.2). Not an A2A version: the binding below is MCP.
 */
export const MCP_PROTOCOL_VERSION = "2025-06-18";
export const CARD_VERSION = "1.1.0";
export const A2A_DOOR = "https://councilof.ai/api/a2a";
export const PUBLIC_AGENT_CARD = "https://councilof.ai/.well-known/agent-card.json";

const EXPLICITLY_NOT = ["certification", "accreditation", "conformity-assessment"];

function placeholderArguments(tool) {
  const required = Array.isArray(tool.inputSchema?.required) ? tool.inputSchema.required : [];
  const args = {};
  for (const key of required) args[key] = `<${key}>`;
  return args;
}

function toolsCallExample(tool) {
  const body = {
    jsonrpc: "2.0",
    id: 1,
    method: "tools/call",
    params: { name: tool.name, arguments: placeholderArguments(tool) },
  };
  return `POST ${LOCK().door} ${JSON.stringify(body)}`;
}

let lockCache;
function LOCK() {
  if (!lockCache) lockCache = readJson("functions/mcp/tool-fleet.lock.json");
  return lockCache;
}

export function buildCards() {
  const lock = LOCK();
  const free = readJson("functions/mcp/gspc-tools.json").tools;
  const paid = readJson("functions/mcp/paid-tools.json").tools;
  const byName = new Map([...free, ...paid].map((t) => [t.name, t]));

  const cards = new Map();
  for (const [names, isPaid] of [[lock.free, false], [lock.paid, true]]) {
    for (const name of names) {
      const tool = byName.get(name);
      if (!tool) throw new Error(`fleet lock names ${name} but no manifest defines it`);
      const examples = [toolsCallExample(tool)];
      if (isPaid) {
        examples.push(
          "Call without x_payment for the x402 payment challenge. Payment travels as the x_payment argument. A challenge is not settlement, delivery or revenue.",
        );
      }
      cards.set(`${name}.json`, {
        name: `Council of AI — ${name}`,
        description: tool.description,
        version: CARD_VERSION,
        provider: { organization: "CSOAI Ltd", url: "https://councilof.ai" },
        supportedInterfaces: [
          { url: lock.door, protocolBinding: "MCP", protocolVersion: MCP_PROTOCOL_VERSION },
        ],
        interface_note:
          `${name} is served by MCP tools/call at POST ${lock.door}. It is not a skill of the A2A door at ${A2A_DOOR}; that door's skills are the ones listed on ${PUBLIC_AGENT_CARD}. This card is generated by scripts/a2a-tool-cards.mjs from the manifests the door serves.`,
        documentationUrl: "https://councilof.ai/llms.txt",
        capabilities: { streaming: false, pushNotifications: false, extendedAgentCard: false },
        defaultInputModes: ["application/json"],
        defaultOutputModes: ["text/plain", "application/json"],
        skills: [
          {
            id: name,
            name,
            description: tool.description,
            tags: ["measurement", "mcp", isPaid ? "x402" : "free"],
            examples,
          },
        ],
        mcp_input_schema: tool.inputSchema ?? { type: "object", properties: {} },
        explicitly_not: EXPLICITLY_NOT,
        mcp_tool: name,
        paid: isPaid,
        did: `did:web:councilof.ai:agents:${name}`,
      });
    }
  }

  const all = [...lock.free, ...lock.paid];
  const index = {
    schema: "csoai.a2a-agent-index/0.1",
    note:
      `${all.length} cards = the ${all.length} MCP tools on POST /mcp (${lock.free.length} free readers, ${lock.paid.length} x402-metered). ` +
      `Each card names POST ${lock.door} with binding MCP — not ${A2A_DOOR}, whose skills are on ${PUBLIC_AGENT_CARD}. ` +
      `Not ${all.length} human analysts. Count and names are locked by functions/mcp/tool-fleet.lock.json; the lock test fails if this index and the door disagree. ` +
      "Cards are generated by scripts/a2a-tool-cards.mjs. Measurement, not certification.",
    count: all.length,
    agents: all.map((id) => ({
      id,
      href: `https://councilof.ai/.well-known/agents/${id}.json`,
      paid: lock.paid.includes(id),
    })),
  };
  cards.set("index.json", index);
  return cards;
}

export const render = (doc) => `${JSON.stringify(doc, null, 2)}\n`;

function main() {
  const mode = process.argv[2];
  if (mode !== "--check" && mode !== "--write") {
    console.error("usage: node scripts/a2a-tool-cards.mjs --check | --write");
    process.exit(2);
  }
  const cards = buildCards();
  const onDisk = new Set(readdirSync(AGENTS_DIR).filter((f) => f.endsWith(".json")));
  const drifted = [];
  for (const [file, doc] of cards) {
    const path = resolve(AGENTS_DIR, file);
    const want = render(doc);
    let have = null;
    try { have = readFileSync(path, "utf8"); } catch { /* missing */ }
    if (have !== want) {
      drifted.push(file);
      if (mode === "--write") writeFileSync(path, want);
    }
    onDisk.delete(file);
  }
  for (const stray of onDisk) drifted.push(`${stray} (not in the fleet lock)`);
  if (mode === "--check") {
    if (drifted.length) {
      console.error(`a2a-tool-cards: ${drifted.length} file(s) differ from the generator:\n  ${drifted.join("\n  ")}`);
      process.exit(1);
    }
    console.log(`a2a-tool-cards: ${cards.size} files match the generator`);
  } else {
    console.log(`a2a-tool-cards: wrote ${drifted.length} file(s); ${cards.size} generated`);
    if (onDisk.size) console.error(`stray files not removed: ${[...onDisk].join(", ")}`);
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
