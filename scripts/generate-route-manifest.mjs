#!/usr/bin/env node
/**
 * generate-route-manifest.mjs — keep the Library IA in sync with App.tsx.
 *
 * Parses every `<Route path="/x" component={Y} />` from App.tsx and emits
 * client/src/data/route-manifest.ts: { path, comp, title } per static route. The Library
 * (data/library-ia.ts) classifies these into the 8 sectors at runtime, so as routes are
 * added/removed the archive updates itself — no hand-maintained list to drift.
 *
 * Wired into `build:client` (alongside generate-sitemap). Fail-SOFT: on any parse problem it
 * leaves the existing manifest untouched rather than shipping an empty archive.
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const APP = join(ROOT, "client/src/App.tsx");
const OUT = join(ROOT, "client/src/data/route-manifest.ts");

try {
  const src = readFileSync(APP, "utf8");
  const re = /<Route\s+path="([^"]+)"\s+component=\{([A-Za-z0-9_]+)\}/g;
  const seen = new Set();
  const rows = [];
  let m;
  while ((m = re.exec(src)) !== null) {
    const [, p, comp] = m;
    if (!p.startsWith("/") || p.includes(":") || seen.has(p)) continue;
    seen.add(p);
    const title = comp
      .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
      .replace(/\bV2\b|\bV3\b/g, "")
      .replace(/\s+/g, " ")
      .trim();
    rows.push({ path: p, comp, title });
  }
  if (rows.length < 50) {
    console.warn(`[route-manifest] only ${rows.length} routes parsed — leaving existing manifest untouched.`);
    process.exit(0);
  }
  rows.sort((a, b) => a.path.localeCompare(b.path));
  const body =
    "// GENERATED by scripts/generate-route-manifest.mjs — do not hand-edit.\n" +
    "// Snapshot of App.tsx routes for the Library IA: path + source component + derived title.\n" +
    "export interface RouteEntry { path: string; comp: string; title: string }\n" +
    "export const ROUTE_MANIFEST: RouteEntry[] = " +
    JSON.stringify(rows, null, 1) +
    ";\n";
  const prev = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (prev !== body) writeFileSync(OUT, body);
  console.log(`[route-manifest] ${rows.length} routes -> client/src/data/route-manifest.ts`);
} catch (e) {
  console.warn(`[route-manifest] skipped (${e.message}) — existing manifest kept.`);
  process.exit(0);
}
