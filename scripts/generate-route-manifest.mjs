#!/usr/bin/env node
/**
 * generate-route-manifest.mjs — keep the Library IA in sync with App.tsx.
 *
 * Parses every `<Route path="/x" component={Y} />` from App.tsx and emits
 * client/src/data/route-manifest.ts: { path, comp, title } per static route. The Library
 * (data/library-ia.ts) classifies these into the 8 sectors at runtime, so as routes are
 * added/removed the archive updates itself — no hand-maintained list to drift.
 *
 * Wired into `build:client` (alongside generate-sitemap). Fail-SOFT: on any parse problem it
 * leaves the existing manifest untouched rather than shipping an empty archive.
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const APP = join(ROOT, "client/src/App.tsx");
const OUT = join(ROOT, "client/src/data/route-manifest.ts");

try {
  const src = readFileSync(APP, "utf8");
  const re = /<Route\s+path="([^"]+)"\s+component=\{([A-Za-z0-9_]+)\}/g;
  // Render-prop routes — <Route path="/x">{() => <SectorAct sector="healthcare" />}</Route> —
  // were invisible to the manifest (2026-08-25 audit: the whole vertical AI-Act and
  // US-state clusters were unreachable through the Library because of this).
  const reRender = /<Route\s+path="([^"]+)"\s*>\s*\{\s*\(\)\s*=>\s*<([A-Za-z0-9_]+)/g;
  const seen = new Set();
  const rows = [];
  // A component name is not a public title. Where the derived title says something the page is not
// (X402Leaderboard is a door board of 402 challenge fields, not a leaderboard), name it here.
// UKAIBill read as "UK AI Bill" in the Library, naming a law that is not in force (6 Oct 2026).
const TITLE_OVERRIDES = {
  X402Leaderboard: "x402 door board",
  UKAIBill: "UK AI rules (no AI statute in force)",
  UKAIBillCompliance: "UK AI rules: what applies today",
};
let m;
  while ((m = reRender.exec(src)) !== null) {
    const [, p, comp] = m;
    if (!p.startsWith("/") || p.includes(":") || seen.has(p) || comp === "ContentReviewNotice") continue;
    seen.add(p);
    const title = (p.slice(1) || comp)
      .split(/[\/-]/).filter(Boolean)
      .map((w) => w[0].toUpperCase() + w.slice(1)).join(" ");
    rows.push({ path: p, comp, title });
  }
  while ((m = re.exec(src)) !== null) {
    const [, p, comp] = m;
    if (!p.startsWith("/") || p.includes(":") || seen.has(p) || comp === "ContentReviewNotice") continue;
    seen.add(p);
    const title = TITLE_OVERRIDES[comp] ?? comp
      .replace(/([a-z0-9])([A-Z])/g, "$1 $2")
      .replace(/\bV2\b|\bV3\b/g, "")
      .replace(/\s+/g, " ")
      .trim();
    rows.push({ path: p, comp, title });
  }
  if (rows.length < 50) {
    if (process.argv.includes("--check")) {
      // In check mode a parse that yields almost nothing is UNCHECKABLE, not
      // clean. Passing here would report "up to date" about a manifest nobody
      // can vouch for.
      console.error(`[route-manifest] only ${rows.length} routes parsed — cannot verify the committed manifest.`);
      process.exit(1);
    }
    console.warn(`[route-manifest] only ${rows.length} routes parsed — leaving existing manifest untouched.`);
    process.exit(0);
  }
  rows.sort((a, b) => a.path.localeCompare(b.path));
  const body =
    "// GENERATED by scripts/generate-route-manifest.mjs — do not hand-edit.\n" +
    "// Snapshot of App.tsx routes for the Library IA: path + source component + derived title.\n" +
    "export interface RouteEntry { path: string; comp: string; title: string }\n" +
    "export const ROUTE_MANIFEST: RouteEntry[] = " +
    JSON.stringify(rows, null, 1) +
    ";\n";

  // --check: the committed manifest must still be what the producer yields.
  //
  // WHY THIS NEEDED A MODE. The manifest is generated during build:client, so
  // by the time any gate reads the file on disk it has already been
  // regenerated and can never be stale. But the COMMITTED copy is a different
  // artefact: it is what link-gate's model of "what the app serves" is built
  // from when it runs against a checkout, and it is what a reader of the
  // repository sees.
  //
  // It was stale. On 2026-11-06 the committed manifest was missing /brand,
  // /him, /refund-policy and /refunds, and still named GpaiObligations for
  // /gpai while App.tsx had moved to GpaiMatrix — because the lane that added
  // those routes (#3938) did not regenerate the file, and nothing anywhere
  // checked.
  if (process.argv.includes("--check")) {
    const current = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
    if (current !== body) {
      console.error(
        "✗ route-manifest: client/src/data/route-manifest.ts is stale — " +
        "run node scripts/generate-route-manifest.mjs and commit the result."
      );
      process.exit(1);
    }
    console.log(`✓ route-manifest: up to date (${rows.length} routes)`);
    process.exit(0);
  }

  const prev = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (prev !== body) writeFileSync(OUT, body);
  console.log(`[route-manifest] ${rows.length} routes -> client/src/data/route-manifest.ts`);
} catch (e) {
  console.warn(`[route-manifest] skipped (${e.message}) — existing manifest kept.`);
  process.exit(0);
}
