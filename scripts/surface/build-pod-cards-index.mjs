#!/usr/bin/env node
/**
 * build-pod-cards-index.mjs — derived index of SIGNED pod (Ollama) measurement cards, by subject.
 *
 * WHY: a requester who commissioned `llama3.2:3b` could only find its cards by guessing file
 * names under /interop/mill-cards-signed/. /api/commissions joins this index so a receipt
 * resolves to the exact public card URLs. Every row is READ FROM THE SIGNED BYTES at build
 * time; nothing is typed. Rows carry the card's own status (the signer's call from n) and
 * never a verdict of their own. Each row also carries what its n EXCLUDES: n is graded_n,
 * and attempted / parse_errors_excluded / transport_errors_excluded are published beside it
 * so "n: 235" can no longer be read as 235 attempts when 237 were made.
 * Output is a build artefact (gitignored), regenerated by
 * build:client, so it can never go stale relative to what master carries.
 *
 *   node scripts/surface/build-pod-cards-index.mjs [--cards DIR] [--out FILE]
 */
import { readFileSync, readdirSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";

export const SCHEMA = "csoai.pod-cards-index/0.1";
const CARD_URL = "https://councilof.ai/interop/mill-cards-signed/";

/** "ollama:llama3.2:3b@sha256:abc…" → { subject: "llama3.2:3b", digest: "sha256:abc…" } */
export function splitModelRef(ref) {
  if (typeof ref !== "string" || !ref.startsWith("ollama:")) return null;
  const rest = ref.slice("ollama:".length);
  const at = rest.indexOf("@");
  return at < 0 ? { subject: rest, digest: null } : { subject: rest.slice(0, at), digest: rest.slice(at + 1) };
}

/**
 * The DENOMINATOR of a measurement card, in the estate's one vocabulary.
 *
 * A row used to publish `n` alone. `n` is graded_n — the pod worker
 * (scripts/runpod_gspc_worker.py) computes graded_n = transport_ok - parse_errors and
 * writes body.n = graded_n — so a reader of `"n": 235, "status": "MEASURED"` could not
 * tell that 237 items were put to the model and 2 were dropped. The exclusions were in
 * the signed bytes the whole time and stopped here.
 *
 * Names are /api/worker's (attempted / parse_errors_excluded / graded_n). `attempted` is
 * DERIVED — the card body carries no such field — and stays null unless n and BOTH
 * exclusion counts are integers on the bytes. A count the card does not publish is null
 * with EXCLUSIONS_ABSENT: zero and absent are different and must stay different.
 *
 * Mirrored in TypeScript by functions/_lib/denominator.ts; the two are held identical by
 * functions/_lib/denominator.parity.test.ts.
 */
export function denominatorFields(body) {
  const b = body && typeof body === "object" ? body : {};
  const ce = b.compute_evidence && typeof b.compute_evidence === "object" ? b.compute_evidence : {};
  const int = (v) => (Number.isInteger(v) ? v : null);
  const n = int(b.n);
  const parse_errors_excluded = int(ce.parse_errors_excluded);
  const transport_errors_excluded = int(ce.transport_errors_excluded);
  const present = (parse_errors_excluded !== null ? 1 : 0) + (transport_errors_excluded !== null ? 1 : 0);
  const exclusions_state =
    present === 2 ? "EXCLUSIONS_PUBLISHED" : present === 1 ? "EXCLUSIONS_PARTIAL" : "EXCLUSIONS_ABSENT";
  const complete = present === 2 && n !== null;
  return {
    n,
    graded_n: complete ? n : null,
    parse_errors_excluded,
    transport_errors_excluded,
    attempted: complete ? n + parse_errors_excluded + transport_errors_excluded : null,
    exclusions_state,
  };
}

export const DENOMINATOR_RULE =
  "A card's n is graded_n: the attempts that produced a parseable label. attempted = graded_n + parse_errors_excluded + transport_errors_excluded, derived — the card body carries no `attempted`. A count the card does not publish is null with EXCLUSIONS_ABSENT, never 0.";

export const BOARD_AXIS_N_IS_NOT_CARD_N =
  "/api/gspc publishes a per-axis n — the item count of that axis's public bank, i.e. the attempts. A card's n is ONE model's graded_n against that bank, so the two differ by exactly that card's excluded attempts. Read `attempted` here before concluding the two numbers disagree; neither is adjusted to match the other.";

export function rowFromCard(name, wrap) {
  const body = wrap && typeof wrap === "object" ? wrap.body : null;
  if (!body || typeof body !== "object") return null;
  const m = splitModelRef(body.model);
  if (!m) return null; // hub / non-pod cards are indexed elsewhere (/api/hub-cards)
  if (typeof wrap.id !== "string" || typeof wrap.signature !== "string") return null;
  const ce = body.compute_evidence && typeof body.compute_evidence === "object" ? body.compute_evidence : {};
  return {
    id: wrap.id,
    file: name,
    url: CARD_URL + name,
    subject: m.subject,
    model_ref: body.model,
    model_digest: m.digest,
    axis: typeof body.axis === "string" ? body.axis : null,
    // n stays where it was and keeps its meaning; the four fields beside it say what
    // that denominator excludes, so it can no longer be read as the attempts.
    ...denominatorFields(body),
    status: typeof body.status === "string" ? body.status : null,
    bank_sha256: typeof ce.bank_sha256 === "string" ? ce.bank_sha256 : null,
    run_id: typeof ce.run_id === "string" ? ce.run_id : null,
    did: typeof wrap.did === "string" ? wrap.did : null,
    signed: true,
    verified_here: false, // the index never verifies; verify the bytes at `url` under did.json
  };
}

export function buildIndex(cardsDir) {
  const rows = [];
  let skipped = 0;
  const names = existsSync(cardsDir) ? readdirSync(cardsDir).filter((f) => f.startsWith("signed-") && f.endsWith(".json")).sort() : [];
  for (const name of names) {
    try {
      const row = rowFromCard(name, JSON.parse(readFileSync(join(cardsDir, name), "utf8")));
      if (row) rows.push(row); else skipped++;
    } catch { skipped++; }
  }
  const subjects = {};
  for (const r of rows) (subjects[r.subject] ||= []).push(r.id);
  const rows_by_exclusions_state = { EXCLUSIONS_PUBLISHED: 0, EXCLUSIONS_PARTIAL: 0, EXCLUSIONS_ABSENT: 0 };
  let rows_with_excluded_attempts = 0;
  for (const r of rows) {
    rows_by_exclusions_state[r.exclusions_state] = (rows_by_exclusions_state[r.exclusions_state] ?? 0) + 1;
    if ((r.parse_errors_excluded ?? 0) + (r.transport_errors_excluded ?? 0) > 0) rows_with_excluded_attempts++;
  }
  return {
    schema: SCHEMA,
    as_of: new Date().toISOString(),
    source: "public/interop/mill-cards-signed/signed-*.json on the deployed commit",
    what: "Signed pod (Ollama) measurement cards by subject. Derived at build time from the signed bytes; never typed; carries each card's own status and no verdict of its own. Not a certificate.",
    verify: "fetch url → verify sha256(canonical body)==id and the Ed25519 signature under the kid in https://csoai.org/.well-known/did.json",
    count: rows.length,
    denominator: {
      rule: DENOMINATOR_RULE,
      vocabulary: "attempted / graded_n / parse_errors_excluded / transport_errors_excluded — the same names /api/worker publishes.",
      board_axis_n_is_not_card_n: BOARD_AXIS_N_IS_NOT_CARD_N,
      rows_by_exclusions_state,
      rows_with_excluded_attempts,
    },
    signed_files_seen: names.length,
    skipped_non_pod_or_unreadable: skipped,
    subjects,
    cards: rows,
  };
}

const isMain = process.argv[1] && import.meta.url.endsWith(process.argv[1].split("/").pop());
if (isMain) {
  const args = process.argv.slice(2);
  const opt = (k, d) => { const i = args.indexOf(k); return i >= 0 ? args[i + 1] : d; };
  const cards = opt("--cards", "public/interop/mill-cards-signed");
  const out = opt("--out", "public/interop/pod-cards-index.json");
  const idx = buildIndex(cards);
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, JSON.stringify(idx, null, 1) + "\n");
  console.log(`pod-cards-index: ${idx.count} pod cards over ${Object.keys(idx.subjects).length} subjects (${idx.signed_files_seen} signed files seen, ${idx.skipped_non_pod_or_unreadable} non-pod/unreadable); ${idx.denominator.rows_with_excluded_attempts} rows excluded attempts, ${idx.denominator.rows_by_exclusions_state.EXCLUSIONS_ABSENT} publish no exclusion counts → ${out}`);
}
