#!/usr/bin/env node
/**
 * Build functions/_middleware.js for the csoai.org deploy (Cloudflare Pages project csoai-site).
 *
 *   node scripts/csoai-site/build-apex-functions.mjs <site-dir> <functions-dir>
 *
 * It lists every file under <site-dir>/.well-known, writes the middleware with that list built
 * in (template: apex-middleware.js beside this file), then loads what it wrote and checks it
 * before anything is uploaded:
 *   - every listed file is handed to the asset server, once, and its response is returned as is;
 *   - a /.well-known/ path that is not listed answers 404 and never reaches the asset server;
 *   - every other path is a 308 to councilof.ai, and cannot be made to leave councilof.ai.
 * Any failure exits 1, so the deploy step that follows does not run.
 *
 * Run by .github/workflows/csoai-site-deploy.yml, as the last step before the upload, so the
 * list is taken after every step that adds a file to .well-known.
 */
import { lstatSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
export const TEMPLATE_PATH = join(HERE, "apex-middleware.js");
export const MARKER = "[/*@WELL_KNOWN_FILES@*/]";

// The build stops if one of these is missing: did:web:csoai.org and the two agent-card names.
export const MUST_KEEP = [
  "/.well-known/did.json",
  "/.well-known/agent-card.json",
  "/.well-known/agent.json",
];

// One path segment. Plain names only, so "the request path equals a listed path" has one
// reading: no spaces, no percent signs, nothing a URL parser would rewrite.
const SAFE_SEGMENT = /^[A-Za-z0-9][A-Za-z0-9._-]*$/;

/** Every file under <siteDir>/.well-known as a URL path, sorted. Throws on anything unclear. */
export function listWellKnownFiles(siteDir) {
  const root = join(siteDir, ".well-known");
  let rootStat;
  try {
    rootStat = lstatSync(root);
  } catch {
    throw new Error(`${root} does not exist: the build holds no /.well-known/ files`);
  }
  if (!rootStat.isDirectory()) throw new Error(`${root} is not a directory`);
  const out = [];
  const walk = (dir, urlDir) => {
    for (const name of readdirSync(dir).sort()) {
      const full = join(dir, name);
      const st = lstatSync(full);
      const urlPath = `${urlDir}/${name}`;
      if (st.isSymbolicLink()) throw new Error(`${urlPath} is a symbolic link; refuse to list it`);
      if (!SAFE_SEGMENT.test(name)) {
        throw new Error(`${urlPath}: name is outside [A-Za-z0-9._-]; rename it or widen the rule on purpose`);
      }
      if (st.isDirectory()) {
        walk(full, urlPath);
      } else if (st.isFile()) {
        // Pages serves x.html at /x (and index.html at the directory), not at the path the
        // file has. The list would then name a path that redirects to one it does not name.
        if (/\.html?$/i.test(name)) {
          throw new Error(`${urlPath}: an HTML file under /.well-known/ is not served at its own path by Pages`);
        }
        out.push(urlPath);
      } else {
        throw new Error(`${urlPath} is neither a file nor a directory`);
      }
    }
  };
  walk(root, "/.well-known");
  return out.sort();
}

/** The middleware source with the list built in. */
export function renderMiddleware(paths, template = readFileSync(TEMPLATE_PATH, "utf8")) {
  const parts = template.split(MARKER);
  if (parts.length !== 2) {
    throw new Error(`template must contain the marker ${MARKER} exactly once (found ${parts.length - 1})`);
  }
  const list = paths.length
    ? `[\n${paths.map((p) => `  ${JSON.stringify(p)},`).join("\n")}\n]`
    : "[]";
  const banner =
    "// GENERATED by scripts/csoai-site/build-apex-functions.mjs in CSOAI-ORG/councilof-ai.\n" +
    "// Do not edit: change the template (scripts/csoai-site/apex-middleware.js) and rebuild.\n";
  return banner + parts[0] + list + parts[1];
}

/** Load a middleware source as a module. A data: URL is always read as ESM, whatever the file is called. */
export async function loadMiddleware(source) {
  return import(`data:text/javascript;base64,${Buffer.from(source, "utf8").toString("base64")}`);
}

/** Ask the middleware for one path. Records whether it called the asset server. */
export async function ask(mod, path, { host = "csoai.org", method = "GET" } = {}) {
  let nextCalls = 0;
  const assetResponse = new Response("asset bytes", { status: 200 });
  const response = await mod.onRequest({
    request: new Request(`https://${host}${path}`, { method }),
    next: async () => {
      nextCalls += 1;
      return assetResponse;
    },
  });
  return { response, nextCalls, passedThrough: response === assetResponse };
}

/** Check a built middleware against the list it was built from. Returns the failures, as text. */
export async function selfCheck(source, paths) {
  const failures = [];
  const mod = await loadMiddleware(source);
  for (const p of paths) {
    const r = await ask(mod, p);
    if (!(r.nextCalls === 1 && r.passedThrough)) failures.push(`${p}: listed, but not handed to the asset server`);
  }
  const strangers = [
    "/.well-known/",
    "/.well-known/no-such-file",
    "/.well-known/no-such-dir/no-such-file.json",
    ...paths.slice(0, 3).flatMap((p) => [`${p}/`, `${p}.bak`, p.replace("/.well-known/", "/.well-known//")]),
  ].filter((p) => !paths.includes(p));
  for (const p of strangers) {
    const r = await ask(mod, p);
    if (r.response.status !== 404) failures.push(`${p}: not listed, answered ${r.response.status}, expected 404`);
    if (r.nextCalls !== 0) failures.push(`${p}: not listed, but reached the asset server`);
  }
  for (const [p, want] of [
    ["/", "https://councilof.ai/"],
    ["/some/page?x=1", "https://councilof.ai/some/page?x=1"],
    ["/.well-known", "https://councilof.ai/.well-known"],
    ["//example.com/x", "https://councilof.ai/example.com/x"],
    ["/\\example.com/x", "https://councilof.ai/example.com/x"],
  ]) {
    const r = await ask(mod, p);
    const loc = r.response.headers.get("location");
    if (r.response.status !== 308 || loc !== want) failures.push(`${p}: ${r.response.status} -> ${loc}, expected 308 -> ${want}`);
    if (r.nextCalls !== 0) failures.push(`${p}: a redirect path reached the asset server`);
  }
  return failures;
}

/** List, render, check, write. Returns what was written. */
export async function buildApexFunctions(siteDir, functionsDir) {
  const paths = listWellKnownFiles(siteDir);
  const missing = MUST_KEEP.filter((p) => !paths.includes(p));
  if (missing.length) throw new Error(`the build lacks ${missing.join(", ")}; refusing to write a middleware that would answer 404 for it`);
  const source = renderMiddleware(paths);
  const failures = await selfCheck(source, paths);
  if (failures.length) throw new Error(`built middleware failed its own check:\n  ${failures.join("\n  ")}`);
  mkdirSync(functionsDir, { recursive: true });
  const file = join(functionsDir, "_middleware.js");
  writeFileSync(file, source);
  return { file, paths };
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  const [siteDir, functionsDir] = process.argv.slice(2);
  if (!siteDir || !functionsDir) {
    console.error("usage: build-apex-functions.mjs <site-dir> <functions-dir>");
    process.exit(2);
  }
  try {
    const { file, paths } = await buildApexFunctions(siteDir, functionsDir);
    console.log(`wrote ${file}`);
    console.log(`${paths.length} /.well-known/ files are served; every other /.well-known/ path answers 404:`);
    for (const p of paths) console.log(`  ${p}`);
  } catch (err) {
    console.error(`FATAL: ${err.message}`);
    process.exit(1);
  }
}
