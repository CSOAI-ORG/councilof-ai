#!/usr/bin/env node
/**
 * generate-redirects.mjs — kill the soft-404 without breaking client-side routing.
 *
 * THE PROBLEM THIS FIXES, measured on production 2026-08-05:
 *
 *     https://csoai.org/zzz-cannot-exist-4a7b   ->  HTTP 200, 36,188 visible characters
 *
 * Cloudflare Pages falls back to index.html for any unmatched path, and since prerendering
 * started working that fallback is now a full, content-rich homepage. Every typo, every stale
 * inbound link, every crawler probe returns a real page with a 200. Search engines will index an
 * unbounded set of URLs all serving duplicate content, and nothing ever deindexes.
 *
 * BEFORE prerendering this was a 60-character shell — bad but low-value. The prerender fix, which
 * was correct and needed, made this defect far more damaging. That is worth stating plainly: the
 * regression came from a good change.
 *
 * WHY NOT JUST ADD 404.html. Because wouter does client-side routing: a cold load of a REAL route
 * like /provenance-finding must receive index.html or the app never boots. A blanket 404 breaks
 * every deep link on the site.
 *
 * THE FIX: enumerate the real routes and let only those fall through to the app.
 *
 *     /real-route/*   /index.html   200      <- app boots, wouter takes over
 *     /*              /404.html     404      <- everything else, honestly
 *
 * Routes come from the SAME parse of App.tsx that generate-sitemap.mjs uses, so the sitemap and
 * the redirect table cannot drift apart. A route that exists is indexable and loadable; a route
 * that does not exist is a 404 in both.
 */
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const APP = join(ROOT, "client/src/App.tsx");
const OUT = join(ROOT, "public/_redirects");

// Static asset directories served directly by Pages — must NOT be routed to the app.
const STATIC_DIRS = ["/arena", "/benchmarks", "/sov-space", "/vendor", "/assets",
                     "/.well-known", "/corpus-watch", "/flywheel"];

const src = readFileSync(APP, "utf8");
const routes = [...src.matchAll(/<Route\s+path=["']([^"']+)["']/g)]
  .map((m) => m[1])
  .filter((p) => p.startsWith("/") && !p.includes(":") && !p.includes("*"))
  .filter((p, i, a) => a.indexOf(p) === i)
  .sort();

// Preserve hand-written rules that already exist — they are consolidation redirects and
// clobbering them would break live inbound links.
const EXISTING = [
  "/gspc-arena     /sov-space?view=arena   308",
  "/sovereign-town /sov-space?view=towns   308",
  "/towns          /sov-space?view=towns   308",
  "/globe          /globe3d.html           308",
];

const lines = [
  "# GENERATED by scripts/generate-redirects.mjs — do not hand-edit.",
  "# Real routes fall through to the SPA; everything else gets an honest 404.",
  "# Route list is parsed from client/src/App.tsx, the same source as sitemap.xml.",
  "",
  "# --- hand-written consolidation redirects (preserved) ---",
  ...EXISTING,
  "",
  "# --- static asset trees: served directly, never routed to the app ---",
  ...STATIC_DIRS.map((d) => `${d}/*  ${d}/:splat  200`),
  "",
  `# --- ${routes.length} real application routes ---`,
  // Cloudflare Pages allows 2,000 STATIC rules but only 100 DYNAMIC (splat) ones. Emitting a
  // `/route/*` splat per route produced 407 dynamic rules, over the cap — Pages would have
  // silently dropped the excess and the catch-all 404 might never have been reached. Only the
  // static asset trees and the final catch-all use splats; the routes themselves are exact.
  ...routes.map((r) => `${r}  /index.html  200`),
  "",
  "# --- everything else does not exist, and now says so ---",
  // SPA catch-all: boot the app for ANY path so wouter can route it (and render its own in-app
  // 404 for genuinely-dead URLs). Enumerating 417 routes exactly kept missing some -> real menu
  // links 404'd. This is the standard SPA-on-Pages rule and ends the recurring broken-link problem.
  "/*  /index.html  200",
  "",
];

writeFileSync(OUT, lines.join("\n"));
console.log(`[redirects] ${routes.length} real routes + ${STATIC_DIRS.length} static trees`);
console.log(`[redirects] unmatched paths now return 404.html with HTTP 404`);
if (!existsSync(join(ROOT, "public/404.html")))
  console.warn("[redirects] WARNING: public/404.html missing — create it or misses will 404 blank");
