#!/bin/bash
# Add vercel.json to failing Python MCP repos. Uses Contents API PUT which
# auto-creates the branch from the `branch` payload field (no separate
# refs/heads call needed). Cleaner than the git/refs approach.
set -u
REPOS=(
    "accessibility-ai-mcp"
    "agent-negotiation-mcp"
    "ad-copy-ai-mcp"
    "a2a-governance-bridge-mcp"
)
BRANCH="fix/vercel-python-mcp"

read -r -d '' VERCEL_JSON <<'EOF' || true
{
  "$schema": "https://openapi.vercel.sh/vercel.json",
  "builds": [
    {
      "src": "server.py",
      "use": "@vercel/python"
    }
  ],
  "routes": [
    {
      "src": "/(.*)",
      "dest": "server.py"
    }
  ]
}
EOF

for repo in "${REPOS[@]}"; do
    full="CSOAI-ORG/${repo}"
    echo "--- $repo ---"

    # 1. Check if vercel.json already exists on target branch
    existing_sha=$(gh api "repos/${full}/contents/vercel.json?ref=${BRANCH}" --jq '.sha // ""' 2>/dev/null)
    if [ -n "$existing_sha" ]; then
        echo "  vercel.json already on ${BRANCH} (sha ${existing_sha:0:8})"
    else
        # 2. Get the existing file sha (if any) on main for the PUT
        main_sha=$(gh api "repos/${full}/contents/vercel.json" --jq '.sha // ""' 2>/dev/null)
        encoded=$(printf '%s' "$VERCEL_JSON" | base64 | tr -d '\n')

        if [ -n "$main_sha" ]; then
            # File exists on main — update it on branch
            result=$(gh api "repos/${full}/contents/vercel.json" -X PUT \
                -f "message=chore(vercel): add Python MCP vercel.json" \
                -f "branch=${BRANCH}" \
                -f "content=${encoded}" \
                -f "sha=${main_sha}" 2>&1)
        else
            # File doesn't exist — create on branch (auto-creates branch)
            result=$(gh api "repos/${full}/contents/vercel.json" -X PUT \
                -f "message=chore(vercel): add Python MCP vercel.json

Vercel was auto-detecting Node and failing on Python MCP manifests.
This explicit vercel.json tells Vercel to use @vercel/python with
server.py as the entry point.

Generated by Mavis — scripts/fix_vercel_python_mcp_v2.sh" \
                -f "branch=${BRANCH}" \
                -f "content=${encoded}" 2>&1)
        fi

        commit_sha=$(echo "$result" | python3 -c "import json,sys; d=json.load(sys.stdin); print(d.get('commit',{}).get('sha','?')[:8])" 2>/dev/null || echo "")
        if [ -z "$commit_sha" ] || [ "$commit_sha" = "?" ]; then
            echo "  ERROR: $result" | head -c 200
            echo
            continue
        fi
        echo "  vercel.json committed (${commit_sha}) on ${BRANCH}"
    fi

    # 3. Open PR if not already open
    existing_pr=$(gh api "repos/${full}/pulls?state=open&head=${BRANCH}" --jq '.[0].number // ""' 2>/dev/null)
    if [ -n "$existing_pr" ]; then
        echo "  PR already open: #${existing_pr}"
        pr_url=$(gh api "repos/${full}/pulls/${existing_pr}" --jq '.html_url' 2>/dev/null)
        echo "    ${pr_url}"
    else
        pr_url=$(gh pr create \
            --repo "${full}" \
            --base main \
            --head "${BRANCH}" \
            --title "fix(vercel): add Python MCP vercel.json (deploy failure fix)" \
            --body "## What

Adds \`vercel.json\` to fix the production deploy failure (Vercel has been emailing errors since 2026-06-12 02:00 UTC).

## Why

These MCPs are Python packages, but Vercel auto-detects Node and tries to \`npm install\` against the \`package.json\` (which exists for tooling/dev only). Explicit \`vercel.json\` tells Vercel to use \`@vercel/python\` with \`server.py\` as the entry point.

## Test

After merge, the next push to main should produce a green Vercel deploy and a \`POST /mcp\` endpoint on the production URL.

Generated by Mavis — \`scripts/fix_vercel_python_mcp_v2.sh\`" 2>&1 | tail -1)
        echo "  PR: ${pr_url}"
    fi
done
echo "=== done ==="
