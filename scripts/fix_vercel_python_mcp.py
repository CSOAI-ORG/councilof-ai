#!/usr/bin/env python3
"""
Add vercel.json to failing Python MCP repos to fix Vercel deploy errors.

The 4 MCPs failing since 2AM (per Vercel emails) all have package.json but
no vercel.json — Vercel auto-detects Node and chokes on Python MCP manifests.
This script:
  1. Reads main branch HEAD
  2. Creates fix/vercel-python-mcp branch
  3. Adds vercel.json (Python build, server.py as entry)
  4. Opens a PR
"""
import base64
import json
import sys
import urllib.request
import urllib.error

TOKEN = "REDACTED-GH-PUSH-PROTECTION-20261113"
HEADERS = {
    "Authorization": f"token {TOKEN}",
    "Accept": "application/vnd.github.v3+json",
    "User-Agent": "Mavis-fix-vercel",
}

VERCEL_JSON = """{
  "$schema": "https://openapi.vercel.sh/vercel.json",
  "builds": [
    {
      "src": "server.py",
      "use": "@vercel/python"
    }
  ],
  "routes": [
    {
      "src": "/(.*)",
      "dest": "server.py"
    }
  ]
}
"""

REPOS = [
    "accessibility-ai-mcp",
    "agent-negotiation-mcp",
    "ad-copy-ai-mcp",
    "a2a-governance-bridge-mcp",
]


def api(method: str, path: str, data: dict | None = None) -> dict:
    url = f"https://api.github.com{path}"
    body = json.dumps(data).encode() if data is not None else None
    req = urllib.request.Request(url, data=body, method=method, headers=HEADERS)
    try:
        with urllib.request.urlopen(req, timeout=30) as r:
            return json.loads(r.read())
    except urllib.error.HTTPError as e:
        body = e.read().decode("utf-8", "ignore")[:300]
        return {"_error": e.code, "_body": body}


def main():
    for repo in REPOS:
        full = f"CSOAI-ORG/{repo}"
        branch = "fix/vercel-python-mcp"

        # 1. Get main HEAD sha
        ref = api("GET", f"/repos/{full}/git/refs/heads/main")
        if "_error" in ref:
            print(f"  {repo}: cannot read main — {ref['_error']}: {ref['_body'][:80]}")
            continue
        main_sha = ref["object"]["sha"]

        # 2. Create branch
        create = api("POST", f"/repos/{full}/git/refs", {
            "ref": f"refs/heads/{branch}",
            "sha": main_sha,
        })
        if "_error" in create and "Reference already exists" not in create.get("_body", ""):
            print(f"  {repo}: branch create failed — {create['_error']}: {create['_body'][:80]}")
            continue

        # 3. Add vercel.json
        encoded = base64.b64encode(VERCEL_JSON.encode()).decode()
        put = api("PUT", f"/repos/{full}/contents/vercel.json", {
            "message": "chore(vercel): add Python MCP vercel.json\n\nFixes Vercel deploy failure by explicitly declaring @vercel/python build with server.py as the entry point. Without this, Vercel auto-detects Node and chokes on the Python MCP manifest.",
            "content": encoded,
            "branch": branch,
        })
        if "_error" in put:
            print(f"  {repo}: vercel.json write failed — {put['_error']}: {put['_body'][:80]}")
            continue
        commit_sha = put.get("commit", {}).get("sha", "?")[:8]
        print(f"  {repo}: vercel.json committed ({commit_sha}) on {branch}")

        # 4. Open PR
        pr_body = (
            "## What\n\n"
            "Adds `vercel.json` to fix the production deploy failure (Vercel has been "
            "emailing errors since 2026-06-12 02:00 UTC).\n\n"
            "## Why\n\n"
            "These MCPs are Python packages, but Vercel auto-detects Node and tries to "
            "`npm install` against the `package.json` (which exists for tooling/dev only). "
            "Explicit `vercel.json` tells Vercel to use `@vercel/python` with `server.py` "
            "as the entry point.\n\n"
            "## Test\n\n"
            "After merge, the next push to main should produce a green Vercel deploy "
            "and a `POST /mcp` endpoint on the production URL.\n\n"
            "Generated by Mavis — `scripts/fix_vercel_python_mcp.py`"
        )
        pr = api("POST", f"/repos/{full}/pulls", {
            "title": "fix(vercel): add Python MCP vercel.json (deploy failure fix)",
            "head": branch,
            "base": "main",
            "body": pr_body,
        })
        if "_error" in pr:
            # check if PR already open
            existing = api("GET", f"/repos/{full}/pulls?state=open&head={branch}")
            if isinstance(existing, list) and existing:
                print(f"    PR already open: #{existing[0]['number']}  {existing[0]['html_url']}")
            else:
                print(f"    PR open failed — {pr['_error']}: {pr['_body'][:80]}")
        else:
            print(f"    PR #{pr['number']} opened: {pr['html_url']}")


if __name__ == "__main__":
    main()
