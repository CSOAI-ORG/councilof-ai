#!/usr/bin/env node
/**
 * build-evidence-index-space — bundle the dashboard's evidence index for the static
 * Hugging Face Space (csoai/gspc-board), from the SAME source files the dashboard pane
 * imports: client/src/components/evidence-index/{space-entry.ts, mount.ts,
 * evidenceIndex.ts, style.css}. One module, two hosts, no second copy to drift.
 *
 *   node scripts/build-evidence-index-space.mjs          write spaces/gspc-board/evidence-index/evidence-index.js
 *   node scripts/build-evidence-index-space.mjs --check  exit 1 if the committed bundle is stale
 *
 * This only writes into the repo. Uploading to Hugging Face is an owner/credential step:
 * scripts/sync_hf_gspc.py and hf-gspc-surface-sync.yml sync an explicit four-file list
 * and deliberately do not include this directory.
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const ENTRY = path.join(REPO, "client/src/components/evidence-index/space-entry.ts");
const OUT = path.join(REPO, "spaces/gspc-board/evidence-index/evidence-index.js");
const CHECK = process.argv.includes("--check");

/** Vite's `?inline` CSS import, reproduced for esbuild: the stylesheet as a string. */
const inlineCss = {
  name: "inline-css",
  setup(b) {
    b.onResolve({ filter: /\.css\?inline$/ }, (args) => ({
      path: path.resolve(args.resolveDir, args.path.replace(/\?inline$/, "")),
      namespace: "inline-css",
    }));
    b.onLoad({ filter: /.*/, namespace: "inline-css" }, (args) => ({
      contents: readFileSync(args.path, "utf8"),
      loader: "text",
    }));
  },
};

export async function bundle() {
  const result = await build({
    entryPoints: [ENTRY],
    bundle: true,
    format: "esm",
    target: "es2020",
    minify: true,
    legalComments: "none",
    charset: "utf8",
    write: false,
    plugins: [inlineCss],
    banner: {
      js: "/* GSPC evidence index — generated by scripts/build-evidence-index-space.mjs from client/src/components/evidence-index. Do not edit. */",
    },
  });
  return result.outputFiles[0].text;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const text = await bundle();
  if (CHECK) {
    const committed = existsSync(OUT) ? readFileSync(OUT, "utf8") : null;
    if (committed !== text) {
      console.error(
        `build-evidence-index-space: STALE — ${path.relative(REPO, OUT)} does not match its sources. Run node scripts/build-evidence-index-space.mjs`,
      );
      process.exit(1);
    }
    console.log(`build-evidence-index-space: OK — ${path.relative(REPO, OUT)} matches its sources`);
  } else {
    mkdirSync(path.dirname(OUT), { recursive: true });
    writeFileSync(OUT, text);
    console.log(`build-evidence-index-space: wrote ${path.relative(REPO, OUT)} (${text.length} bytes)`);
  }
}
