#!/usr/bin/env python3
"""Publish a verified daily report and its browse-only projection to Hugging Face."""

import argparse
import datetime
import json
import os
import re
import subprocess
import sys
import tempfile
import urllib.request
from pathlib import Path

import check_report

HERE = Path(__file__).resolve().parent
REPO_ID = "csoai/gspc-daily-reports"
CARD = HERE / "dataset-card.md"
AXIS_ID = re.compile(r"[a-z0-9][a-z0-9-]*")
CORRECTION_ID = re.compile(r"C-[0-9]{4}-[0-9]{4}-[0-9]{2}")


def get_token():
    token = (os.environ.get("HF_TOKEN") or "").strip()
    if token:
        return token
    token_file = Path("~/.cache/huggingface/token").expanduser()
    return token_file.read_text().strip() if token_file.exists() else None


def viewer_rows(date, raw):
    """Publish an index, with exact source links and no scores or free text."""
    if datetime.date.fromisoformat(date).isoformat() != date:
        raise ValueError("expected ISO report date")
    report = json.loads(raw)
    if report.get("report_date") != date:
        raise ValueError("projection date differs from report")
    axes = report["axes"]
    if not isinstance(axes, dict) or not axes:
        raise ValueError("report has no axes")
    report_url = f"https://huggingface.co/datasets/{REPO_ID}/resolve/main/reports/{date}/daily-report-{date}.json"
    digest = check_report.sha256_hex(raw)
    for name, axis in sorted(axes.items()):
        if not AXIS_ID.fullmatch(name) or not isinstance(axis, dict):
            raise ValueError("invalid axis")
        held = axis.get("withheld")
        correction = held.get("entry") if isinstance(held, dict) else ""
        if held and (not isinstance(correction, str) or not CORRECTION_ID.fullmatch(correction)):
            raise ValueError("held axis has no valid correction ID")
        state = axis.get("derived_state")
        if not isinstance(state, str) or not re.fullmatch(r"[A-Z][A-Z0-9_-]*", state):
            raise ValueError("invalid report evidence state")
        yield {
            "report_date": date,
            "axis": name,
            "evidence_state": state,
            "quotation_held": bool(held),
            "correction": correction,
            "report_url": report_url,
            "report_sha256": digest,
        }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", required=True, help="the directory generated by generate_daily_report.py")
    ap.add_argument("date", nargs="?")
    args = ap.parse_args()
    root = Path(args.dir)
    date = args.date.strip() if args.date else ""
    if not date:
        candidates = sorted(root.glob("daily-report-*.json"))
        if not candidates:
            print("NO_REPORT — no daily-report-*.json found")
            return 2
        date = candidates[-1].stem.removeprefix("daily-report-")
    try:
        if datetime.date.fromisoformat(date).isoformat() != date:
            raise ValueError
    except ValueError:
        print("REFUSED — invalid report date")
        return 3

    files = {ext: root / f"daily-report-{date}.{ext}" for ext in ("md", "json", "sig")}
    check_path = root / f"report-check-{date}.json"
    if not all(p.is_file() for p in (*files.values(), check_path)):
        print("NO_REPORT — a report file or its check is missing")
        return 2
    raw = files["json"].read_bytes()
    checked = json.loads(check_path.read_bytes())
    signature = json.loads(files["sig"].read_bytes())
    key = checked.get("key") or {}
    expected_key = check_report.BOARD_KEY
    if (checked.get("result") != "PASS" or checked.get("signature") != "VERIFIES"
            or checked.get("report_json_sha256") != check_report.sha256_hex(raw)
            or any(key.get(k) != expected_key[k] for k in ("did", "public_key_hex"))
            or check_report.signature_state(date, raw, signature, expected_key)[0] != "VERIFIES"):
        print("REFUSED — the report bytes, signature and pinned board check must agree")
        return 3

    token = get_token()
    if not token:
        print("NO_HF_TOKEN — nothing published")
        return 2
    from huggingface_hub import CommitOperationAdd, HfApi

    projection = b"".join(check_report.canon(row) + b"\n" for row in viewer_rows(date, raw))
    uploads = {f"reports/{date}/{p.name}": p.read_bytes() for p in (files["md"], files["sig"], check_path)}
    uploads[f"reports/{date}/{files['json'].name}"] = raw
    uploads[f"viewer/{date}.jsonl"] = projection
    uploads["README.md"] = CARD.read_bytes()

    # Scan exactly the same bytes that go into the Hub commit below.
    with tempfile.TemporaryDirectory(prefix="gspc-daily-publication-") as staging:
        for path, data in uploads.items():
            dest = Path(staging) / path
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_bytes(data)
        gate = HERE.parent / "privacy" / "publication_gate.py"
        if subprocess.run([sys.executable, str(gate), staging], check=False).returncode:
            return 3

    api = HfApi(token=token)
    parent = api.repo_info(repo_id=REPO_ID, repo_type="dataset", revision="main").sha
    commit = api.create_commit(
        repo_id=REPO_ID, repo_type="dataset", revision="main", parent_commit=parent,
        operations=[CommitOperationAdd(path_in_repo=p, path_or_fileobj=b) for p, b in uploads.items()],
        commit_message=f"Publish verified GSPC daily report {date}",
    )
    for path, expected in uploads.items():
        url = f"https://huggingface.co/datasets/{REPO_ID}/resolve/{commit.oid}/{path}"
        request = urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0 csoai-daily-report/0.1"})
        try:
            with urllib.request.urlopen(request, timeout=30) as response:
                exact = response.status == 200 and response.read(len(expected) + 1) == expected
        except OSError:
            exact = False
        if not exact:
            print(f"READBACK_FAILED — {url}")
            return 3
        print(f"OK exact bytes — {url}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
