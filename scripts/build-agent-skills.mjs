#!/usr/bin/env node
// SPDX-License-Identifier: Apache-2.0
// Agent Skills discovery index (Agent Skills Discovery RFC v0.2.0, https://github.com/cloudflare/agent-skills-discovery-rfc;
// schema https://schemas.agentskills.io/discovery/0.2.0/schema.json), derived from the A2A skills the served agent card
// declares — never typed here. One SKILL.md per card skill at /.well-known/agent-skills/<id>/SKILL.md and the index at
// /.well-known/agent-skills/index.json with each artifact's sha256 digest.
//
//   node scripts/build-agent-skills.mjs          # write
//   node scripts/build-agent-skills.mjs --check  # exit 1 if the committed files differ from a fresh render
//
// The card (public/.well-known/agent-card.json) is the source; public/.well-known/agent.json is byte-identical to it,
// SKILL_IDS in functions/api/a2a.ts must equal its skill ids (functions/api/a2a.test.ts), and so must this index
// (functions/_lib/agentSkillsIndex.test.ts). A skill added to the card appears here on the next render; one removed
// from the card disappears (its directory is deleted), so the index can never advertise a skill the router refuses.
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const REPO = join(dirname(fileURLToPath(import.meta.url)), "..");
const CARD = join(REPO, "public/.well-known/agent-card.json");
const OUT = join(REPO, "public/.well-known/agent-skills");
const SCHEMA = "https://schemas.agentskills.io/discovery/0.2.0/schema.json";
const A2A = "https://councilof.ai/api/a2a";
const NAME_RE = /^[a-z0-9]+(-[a-z0-9]+)*$/;

const card = JSON.parse(readFileSync(CARD, "utf8"));
const oneLine = (s) => String(s ?? "").replace(/\s+/g, " ").trim();
const yamlStr = (s) => JSON.stringify(oneLine(s)); // a JSON string is a valid YAML double-quoted scalar

function skillMd(s) {
  const examples = (s.examples ?? []).map((e) => (typeof e === "string" ? e : JSON.stringify(e)));
  const lines = [
    "---",
    `name: ${s.id}`,
    `description: ${yamlStr(s.description)}`,
    "---",
    "",
    `# ${oneLine(s.name)}`,
    "",
    oneLine(s.description),
    "",
    "## How to call it",
    "",
    `This is an A2A skill of the Council of AI measurement agent (agent card: https://councilof.ai/.well-known/agent-card.json).`,
    `Send \`SendMessage\` to \`POST ${A2A}\` with header \`A2A-Version: 1.0\`; \`params.message\` carries a \`messageId\` and \`parts\`,`,
    `and one structured part selects the skill: \`{"data": {"skill": "${s.id}", "input": {...}}, "mediaType": "application/json"}\`.`,
    `Calling it needs no account, key or registration (see https://councilof.ai/auth.md).`,
    "",
  ];
  if (examples.length) lines.push("## Examples", "", ...examples.map((e) => `- ${oneLine(e)}`), "");
  if ((s.tags ?? []).length) lines.push(`Tags: ${s.tags.map(oneLine).join(", ")}`, "");
  lines.push(
    "Measurement, never certification: an answer is evidence about specific bytes at a specific time, not a grade or mark.",
    "Generated by scripts/build-agent-skills.mjs from the agent card; do not hand-edit.",
    "",
  );
  return lines.join("\n");
}

const files = new Map();
const skills = [];
for (const s of card.skills ?? []) {
  if (!NAME_RE.test(s.id)) throw new Error(`agent-card skill id ${JSON.stringify(s.id)} is not lowercase alphanumeric + hyphens`);
  const md = skillMd(s);
  files.set(`${s.id}/SKILL.md`, md);
  skills.push({
    name: s.id,
    type: "skill-md",
    description: oneLine(s.description),
    url: `/.well-known/agent-skills/${s.id}/SKILL.md`,
    digest: `sha256:${createHash("sha256").update(md).digest("hex")}`,
  });
}
const index = { $schema: SCHEMA, skills };
files.set("index.json", JSON.stringify(index, null, 2) + "\n");

if (process.argv.includes("--check")) {
  const bad = [];
  for (const [p, want] of files) {
    const f = join(OUT, p);
    if (!existsSync(f) || readFileSync(f, "utf8") !== want) bad.push(p);
  }
  const onDisk = existsSync(OUT) ? readdirSync(OUT).filter((d) => d !== "index.json") : [];
  for (const d of onDisk) if (!files.has(`${d}/SKILL.md`)) bad.push(`${d}/ (not a card skill)`);
  if (bad.length) {
    console.error(`agent-skills: DRIFT ${bad.join(", ")} — run node scripts/build-agent-skills.mjs`);
    process.exit(1);
  }
  console.log(`agent-skills: ${skills.length} skills match the agent card`);
} else {
  if (existsSync(OUT)) for (const d of readdirSync(OUT)) if (d !== "index.json" && !files.has(`${d}/SKILL.md`)) rmSync(join(OUT, d), { recursive: true });
  for (const [p, body] of files) {
    mkdirSync(dirname(join(OUT, p)), { recursive: true });
    writeFileSync(join(OUT, p), body);
  }
  console.log(`agent-skills: wrote ${skills.length} skills + index.json`);
}
