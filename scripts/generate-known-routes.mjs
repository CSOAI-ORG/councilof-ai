#!/usr/bin/env node
/**
 * generate-known-routes.mjs — the edge's copy of "which paths are real routes".
 *
 * WHY THIS EXISTS
 * ---------------
 * On Cloudflare Pages the SPA used to boot for EVERY path via `/*  /index.html  200`
 * in _redirects. wouter then falls through to `<Route component={NotFound} />` (App.tsx)
 * and paints a not-found UI — but the HTTP status stayed 200. To a crawler that is a
 * soft-404: every one of the ~350 sitemap URLs, and every typo, answers 200 with a real
 * page. crawler-view-gate.mjs reds out on it, and search engines index an unbounded set.
 *
 * The catch-all is now gone from _redirects; functions/_middleware.ts restores SPA booting
 * but with an HONEST status: 200 for a path the app actually has a `<Route path>` for,
 * 404 for one it does not. This script gives the middleware that list, parsed from the SAME
 * `<Route path="...">` source generate-sitemap.mjs / generate-redirects.mjs read, so the
 * edge's idea of "real" can never drift from the app's.
 *
 * It emits functions/_lib/known-routes.js — a plain ESM module (underscore dir => Pages does
 * not treat it as a route, but a Function may import it). Each `<Route path>` becomes an
 * anchored regex source; `:param` segments match one path segment, mirroring wouter.
 *
 * Wired into `build:client`. Fail-SOFT: on a suspiciously small parse it leaves the existing
 * module untouched rather than shipping a list that would 404 real pages.
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const APP = join(ROOT, "client/src/App.tsx");
const OUT_DIR = join(ROOT, "functions/_lib");
const OUT = join(OUT_DIR, "known-routes.js");

/** Turn a wouter `<Route path>` into an anchored regex source (trailing slash optional). */
function toPattern(routePath) {
  const body = routePath
    .split("/")
    .map((seg) => {
      if (seg === "") return "";
      if (seg.startsWith(":")) return "[^/]+";          // :param -> one segment
      if (seg === "*") return ".*";                     // (none today, but be safe)
      return seg.replace(/[.*+?^${}()|[\]\\]/g, "\\$&"); // escape literals
    })
    .join("/");
  return "^" + body + "/?$";
}

try {
  const src = readFileSync(APP, "utf8");
  const paths = [...src.matchAll(/<Route\s+path=["']([^"']+)["']/g)]
    .map((m) => m[1])
    .filter((p) => p.startsWith("/"))
    .filter((p, i, a) => a.indexOf(p) === i)
    .sort();

  if (paths.length < 50) {
    console.warn(`[known-routes] only ${paths.length} routes parsed — leaving existing module untouched.`);
    process.exit(0);
  }

  const patterns = paths.map(toPattern);
  const body =
    "// GENERATED by scripts/generate-known-routes.mjs — do not hand-edit.\n" +
    "// Anchored regex sources for every <Route path> in App.tsx (the pathless\n" +
    "// NotFound catch-all is intentionally excluded). functions/_middleware.ts uses\n" +
    "// these to serve index.html with an HONEST status: 200 for a declared route,\n" +
    "// 404 for a path the app has no route for.\n" +
    `export const ROUTE_PATTERNS = ${JSON.stringify(patterns, null, 1)};\n`;

  if (!existsSync(OUT_DIR)) mkdirSync(OUT_DIR, { recursive: true });
  const prev = existsSync(OUT) ? readFileSync(OUT, "utf8") : "";
  if (prev !== body) writeFileSync(OUT, body);
  console.log(`[known-routes] ${patterns.length} route patterns -> functions/_lib/known-routes.js`);
} catch (e) {
  console.warn(`[known-routes] skipped (${e.message}) — existing module kept.`);
  process.exit(0);
}
