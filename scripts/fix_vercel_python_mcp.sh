#!/bin/bash
# Add vercel.json to failing Python MCP repos. Uses gh CLI (handles SSL correctly).
set -e
TOKEN="REDACTED-GH-PUSH-PROTECTION-20261113"
REPOS=(
    "accessibility-ai-mcp"
    "agent-negotiation-mcp"
    "ad-copy-ai-mcp"
    "a2a-governance-bridge-mcp"
)
BRANCH="fix/vercel-python-mcp"

read -r -d '' VERCEL_JSON <<'EOF' || true
{
  "$schema": "https://openapi.vercel.sh/vercel.json",
  "builds": [
    {
      "src": "server.py",
      "use": "@vercel/python"
    }
  ],
  "routes": [
    {
      "src": "/(.*)",
      "dest": "server.py"
    }
  ]
}
EOF

for repo in "${REPOS[@]}"; do
    full="CSOAI-ORG/${repo}"
    echo "--- $repo ---"

    # 1. Get main HEAD sha
    main_sha=$(gh api "repos/${full}/git/refs/heads/main" --jq '.object.sha' 2>/dev/null)
    if [ -z "$main_sha" ]; then
        echo "  cannot read main, skipping"
        continue
    fi

    # 2. Create branch (ignore 422 = already exists)
    gh api "repos/${full}/git/refs" -X POST \
        -f "ref=refs/heads/${BRANCH}" \
        -f "sha=${main_sha}" 2>/dev/null || true

    # 3. Check if vercel.json already exists on branch
    existing_sha=$(gh api "repos/${full}/contents/vercel.json?ref=${BRANCH}" --jq '.sha' 2>/dev/null || echo "")

    if [ -n "$existing_sha" ] && [ "$existing_sha" != "null" ]; then
        echo "  vercel.json already on ${BRANCH} (sha ${existing_sha:0:8}), skipping write"
    else
        encoded=$(echo "$VERCEL_JSON" | base64)
        result=$(gh api "repos/${full}/contents/vercel.json" -X PUT \
            -f "message=chore(vercel): add Python MCP vercel.json (fixes deploy failure)

Vercel was auto-detecting Node and failing on Python MCP manifests.
This explicit vercel.json tells Vercel to use @vercel/python with
server.py as the entry point.

Generated by Mavis — scripts/fix_vercel_python_mcp.sh" \
            -f "branch=${BRANCH}" \
            -f "content=${encoded}" 2>&1)
        commit_sha=$(echo "$result" | python3 -c "import json,sys; d=json.load(sys.stdin); print(d.get('commit',{}).get('sha','?')[:8])" 2>/dev/null || echo "?")
        echo "  vercel.json committed (${commit_sha}) on ${BRANCH}"
    fi

    # 4. Open PR if not already open
    existing_pr=$(gh api "repos/${full}/pulls?state=open&head=${BRANCH}" --jq '.[0].number' 2>/dev/null || echo "")
    if [ -n "$existing_pr" ] && [ "$existing_pr" != "null" ]; then
        echo "  PR already open: #${existing_pr}"
    else
        pr=$(gh pr create \
            --repo "${full}" \
            --base main \
            --head "${BRANCH}" \
            --title "fix(vercel): add Python MCP vercel.json (deploy failure fix)" \
            --body "## What

Adds \`vercel.json\` to fix the production deploy failure (Vercel has been emailing errors since 2026-06-12 02:00 UTC).

## Why

These MCPs are Python packages, but Vercel auto-detects Node and tries to \`npm install\` against the \`package.json\` (which exists for tooling/dev only). Explicit \`vercel.json\` tells Vercel to use \`@vercel/python\` with \`server.py\` as the entry point.

## Test

After merge, the next push to main should produce a green Vercel deploy and a \`POST /mcp\` endpoint on the production URL.

Generated by Mavis — \`scripts/fix_vercel_python_mcp.sh\`" 2>&1)
        echo "  PR: $(echo "$pr" | tail -1)"
    fi
done
echo "=== done ==="
