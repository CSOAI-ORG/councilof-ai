#!/usr/bin/env node
// nsite_presence_publish.mjs — publish the N-site presence ledger into Busabase and onto the
// public surface.
//
// The hunt has measured 1,200+ surfaces and written an evidence bundle for each. Until now
// nothing consumed those bundles. This closes the loop: the ledger is the lane's output
// rendered as a checkable table, stored in the estate's substrate (Busabase) and published as
// a dated artefact a reader can verify.
//
// It also carries the failures forward. The ledger's three states are VERIFIED, UNVERIFIABLE
// and MISSING, and the UNVERIFIABLE rows are published with both digests side by side. A
// ledger that only published its successes would be a scoreboard, not a measurement.
//
// Usage:
//   node tools/sites/nsite_presence_publish.mjs \
//     --ledger evidence/sites-census/nsite-presence-ledger.json \
//     --base   bsemvq82v196c7yylx \
//     --origin http://127.0.0.1:15430

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname } from 'node:path';
import { createHash } from 'node:crypto';

const argv = process.argv.slice(2);
const arg = (k, d = null) => {
  const i = argv.indexOf(`--${k}`);
  return i >= 0 && argv[i + 1] ? argv[i + 1] : d;
};
const LEDGER = arg('ledger', 'evidence/sites-census/nsite-presence-ledger.json');
const BASE = arg('base', 'bsemvq82v196c7yylx');
const ORIGIN = arg('origin', 'http://127.0.0.1:15430');
const PUBLIC = arg('public', 'public/interop/nsite-presence-ledger.json');

const raw = readFileSync(LEDGER, 'utf8');
const ledger = JSON.parse(raw);
const ledgerSha = createHash('sha256').update(raw).digest('hex');

// ---- the public artefact -------------------------------------------------------
// The published copy carries the ledger's own digest, so a reader can prove the table they
// are reading is the table that was produced.
const published = {
  ...ledger,
  ledger_sha256: ledgerSha,
  ledger_path: LEDGER,
  published_at: new Date().toISOString().replace(/\.\d+Z$/, 'Z'),
};
mkdirSync(dirname(PUBLIC), { recursive: true });
writeFileSync(PUBLIC, `${JSON.stringify(published, null, 2)}\n`);
console.log(`wrote ${PUBLIC}  (ledger_sha256 ${ledgerSha.slice(0, 16)}…)`);

// ---- Busabase -------------------------------------------------------------------
const FIELDS = [
  ['domain', 'text', true],
  ['result', 'text', false],
  ['presence', 'text', false],
  ['classification', 'text', false],
  ['observed', 'number', false],
  ['score', 'number', false],
  ['at', 'text', false],
  ['event_hash', 'text', false],
  ['bundle_sha256', 'text', false],
  ['evidence_state', 'text', false],
  ['as_of', 'text', false],
];

async function ensureBase() {
  const r = await fetch(`${ORIGIN}/api/v1/bases?limit=100`);
  const j = await r.json().catch(() => ({}));
  const found = (j.bases || []).find((b) => b.slug === 'nsite-presence');
  if (found) return { id: found.id, created: false };
  const res = await fetch(`${ORIGIN}/api/v1/bases`, {
    method: 'POST',
    headers: { 'content-type': 'application/json' },
    body: JSON.stringify({
      type: 'base',
      slug: 'nsite-presence',
      name: 'nsite-presence',
      description:
        'N-site presence ledger: one row per surface the onboard lane measured, with the ' +
        'evidence digest it pinned and whether that digest still verifies. UNVERIFIABLE is a ' +
        'published state, not a hidden one. Generated by tools/sites/nsite_presence_publish.mjs.',
      fields: FIELDS.map(([slug, type, required]) => ({ slug, name: slug, type, required })),
      message: 'N-site presence ledger base',
      submittedBy: 'nsite-presence-publish',
    }),
  });
  const j2 = await res.json().catch(() => ({}));
  if (!j2.id) {
    console.error('could not create the base:', JSON.stringify(j2).slice(0, 300));
    process.exit(1);
  }
  // node_create does not always apply the field list; add them explicitly.
  for (const [slug, type, required] of FIELDS) {
    await fetch(`${ORIGIN}/api/v1/bases/${j2.id}/fields/change-request`, {
      method: 'POST',
      headers: { 'content-type': 'application/json' },
      body: JSON.stringify({ operation: 'add', slug, name: slug, fieldType: type, required, message: `add ${slug}`, submittedBy: 'nsite-presence-publish' }),
    });
  }
  return { id: j2.id, created: true };
}

const base = await ensureBase();
console.log(`base ${base.slug ?? BASE} (${base.id}) ${base.created ? 'created' : 'existing'}`);

const existing = new Map();
for (let cursor = null; ; ) {
  const u = `${ORIGIN}/api/v1/records?baseId=${base.id}&limit=100${cursor ? `&cursor=${encodeURIComponent(cursor)}` : ''}`;
  const j = await fetch(u).then((r) => r.json()).catch(() => ({}));
  for (const rec of j.records || []) {
    const dom = rec.headCommit?.payload?.domain;
    if (dom) existing.set(dom, rec.id);
  }
  cursor = j.nextCursor ?? null;
  if (!cursor) break;
}

const updates = [];
const creates = [];
for (const r of ledger.rows || []) {
  const fields = {
    domain: r.domain,
    result: r.result ?? '',
    presence: r.presence ?? '',
    classification: r.classification ?? '',
    observed: typeof r.observed === 'number' ? r.observed : 0,
    score: typeof r.score === 'number' ? r.score : 0,
    at: r.at ?? '',
    event_hash: r.event_hash ?? '',
    bundle_sha256: r.bundle_sha256 ?? '',
    evidence_state: r.evidence_state,
    as_of: ledger.as_of,
  };
  const id = existing.get(r.domain);
  if (id) updates.push({ recordId: id, fields });
  else creates.push(fields);
}

const out = { updated: 0, created: 0, pending: 0, errors: [] };
const CHUNK = 300;

if (updates.length) {
  for (let i = 0; i < updates.length; i += CHUNK) {
    const res = await fetch(`${ORIGIN}/api/v1/bases/${base.id}/records/bulk-update-change-request`, {
      method: 'POST',
      headers: { 'content-type': 'application/json' },
      body: JSON.stringify({
        updates: updates.slice(i, i + CHUNK),
        message: `N-site presence ledger ${ledger.as_of}`,
        submittedBy: 'nsite-presence-publish',
        autoMerge: true,
      }),
    });
    const j = await res.json().catch(() => ({}));
    out.updated += updates.slice(i, i + CHUNK).length;
    if (j.status && j.status !== 'merged') out.pending += 1;
    if (j.error) out.errors.push(String(j.error));
  }
}
if (creates.length) {
  for (let i = 0; i < creates.length; i += CHUNK) {
    const res = await fetch(`${ORIGIN}/api/v1/bases/${base.id}/records/bulk-change-request`, {
      method: 'POST',
      headers: { 'content-type': 'application/json' },
      body: JSON.stringify({
        records: creates.slice(i, i + CHUNK),
        message: `N-site presence ledger ${ledger.as_of}`,
        submittedBy: 'nsite-presence-publish',
        autoMerge: true,
      }),
    });
    const j = await res.json().catch(() => ({}));
    out.created += creates.slice(i, i + CHUNK).length;
    if (j.status && j.status !== 'merged') out.pending += 1;
    if (j.error) out.errors.push(String(j.error));
  }
}

console.log(JSON.stringify({ ...out, base: base.id, ledger_sha256: ledgerSha }, null, 2));
if (out.pending) console.log('\nSome changes are PENDING REVIEW — a human must approve them.');
